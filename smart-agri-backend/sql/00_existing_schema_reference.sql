-- ============================================================================
-- Reference schema for the AgriBot operational database (Supabase/Postgres).
--
-- This documents what is ALREADY LIVE in the project's Supabase instance, so
-- the app is reproducible from a fresh clone instead of only existing in one
-- hosted database. It is written to be safe to run against the live project
-- too: every statement is idempotent (CREATE ... IF NOT EXISTS / CREATE OR
-- REPLACE), so running it again is a no-op where the object already exists.
--
-- Run in the Supabase SQL editor before 01_system_alerts.sql and
-- 02_rain_prediction_enabled.sql.
-- ============================================================================

-- ── user_accounts ────────────────────────────────────────────────────────────
create table if not exists public.user_accounts (
  id bigint generated by default as identity not null,
  username character varying(50) not null,
  email character varying(255) not null,
  user_password_hash text not null,
  system_control_password_hash text not null,
  account_status character varying(20) not null default 'active'::character varying,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  phone character varying(20) null,
  constraint user_accounts_pkey primary key (id),
  constraint user_accounts_email_key unique (email),
  constraint user_accounts_username_key unique (username),
  constraint user_accounts_account_status_check check (
    (account_status)::text = any (
      (array['active'::character varying, 'disabled'::character varying])::text[]
    )
  )
);

-- ── system_switches ──────────────────────────────────────────────────────────
create table if not exists public.system_switches (
