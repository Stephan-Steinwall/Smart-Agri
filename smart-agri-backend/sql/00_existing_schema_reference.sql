create or replace function public.update_latest_reading_time()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists latest_reading_updated_at on public.latest_soil_reading;
create trigger latest_reading_updated_at
  before update on public.latest_soil_reading
  for each row
  execute function public.update_latest_reading_time();

