-- ── "Wireless sensor Soil Analysis data" (farmer-labeled samples) ──────────
create table if not exists public."Wireless sensor Soil Analysis data" (
  id uuid not null default gen_random_uuid(),
  saved_at timestamp with time zone not null default now(),
  soil_sample_label text not null,
  soil_moisture double precision not null,
  temperature double precision not null,
  soil_ph double precision not null,
  soil_conductivity double precision not null,
  soil_health_score integer null,
  nitrogen integer null,
  phosphorus integer null,
  potassium integer null,
  tds double precision null,
  salinity double precision null,
  recommended_crop text null,
  recommendation_reason text null,
  device_id text not null default 'agribot_receiver_01'::text,
  crop_label text null,
  reading_at timestamp with time zone null,
  prediction_confidence double precision null,
  model_version text null,
  label_status text not null default 'pending'::text,
  labelled_by text null,
  verified_by text null,
  verified_at timestamp with time zone null,
  constraint wireless_soil_analysis_pkey primary key (id),
  constraint valid_soil_health_score check (
    soil_health_score is null or (soil_health_score >= 0 and soil_health_score <= 100)
  ),
  constraint valid_wireless_crop_label check (
    crop_label is null or char_length(trim(both from crop_label)) > 0
  ),
  constraint valid_wireless_label_status check (
    label_status = any (array['pending'::text, 'verified'::text, 'rejected'::text])
  ),
  constraint valid_wireless_nitrogen check (nitrogen is null or nitrogen >= 0),
  constraint valid_wireless_phosphorus check (phosphorus is null or phosphorus >= 0),
  constraint valid_wireless_potassium check (potassium is null or potassium >= 0),
  constraint valid_wireless_prediction_confidence check (
    prediction_confidence is null or (prediction_confidence >= 0 and prediction_confidence <= 100)
  ),
  constraint valid_wireless_salinity check (salinity is null or salinity >= 0),
  constraint valid_wireless_soil_conductivity check (soil_conductivity >= 0),
  constraint valid_wireless_soil_moisture check (soil_moisture >= 0 and soil_moisture <= 100),
  constraint valid_wireless_soil_ph check (soil_ph >= 0 and soil_ph <= 14),
  constraint valid_wireless_soil_sample_label check (char_length(trim(both from soil_sample_label)) > 0),
  constraint valid_wireless_tds check (tds is null or tds >= 0)
);

create index if not exists wireless_soil_analysis_crop_label_index
  on public."Wireless sensor Soil Analysis data" using btree (crop_label);
create index if not exists wireless_soil_analysis_saved_at_index
  on public."Wireless sensor Soil Analysis data" using btree (saved_at desc);
create index if not exists wireless_soil_analysis_label_status_index
  on public."Wireless sensor Soil Analysis data" using btree (label_status);
create index if not exists wireless_soil_analysis_device_saved_index
  on public."Wireless sensor Soil Analysis data" using btree (device_id, saved_at desc);
create index if not exists wireless_soil_analysis_verified_training_index
  on public."Wireless sensor Soil Analysis data" using btree (crop_label, saved_at desc)
  where (label_status = 'verified'::text);
create unique index if not exists wireless_soil_unique_reading_crop_index
  on public."Wireless sensor Soil Analysis data" using btree (device_id, reading_at, crop_label)
  where (reading_at is not null and crop_label is not null);

create or replace function public.set_soil_label_verification_time()
returns trigger
language plpgsql
as $$
begin
  if new.label_status = 'verified' and (old.label_status is distinct from 'verified') then
    new.verified_at = now();
  end if;
  return new;
end;
$$;

drop trigger if exists set_soil_label_verification_time_trigger on public."Wireless sensor Soil Analysis data";
create trigger set_soil_label_verification_time_trigger
  before update of label_status on public."Wireless sensor Soil Analysis data"
  for each row
  execute function public.set_soil_label_verification_time();
